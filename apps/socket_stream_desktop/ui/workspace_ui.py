"""Native GTK workspace construction, separate from capture/process control."""
from shortcuts import ACTIONS, ACTION_LABELS
from ui_theme import install_theme, style


def build_workspace(app):
    from gi.repository import Gtk, Pango

    style(app, "ss-app")
    install_theme(app.get_screen())
    app.set_default_size(1000, 750)
    app.set_size_request(840, 580)
    header = Gtk.HeaderBar(title="SocketStream", subtitle="Your practice workspace")
    header.set_show_close_button(True)
    app.set_titlebar(header)
    open_panel = Gtk.Button(label="Open answer panel")
    open_panel.connect("clicked", app.show_answer_panel)
    header.pack_end(open_panel)
    root = Gtk.Box(orientation=Gtk.Orientation.VERTICAL)
    app.add(root)
    shell = Gtk.Box()
    root.pack_start(shell, True, True, 0)
    nav = style(Gtk.Box(orientation=Gtk.Orientation.VERTICAL, spacing=6), "ss-nav")
    nav.set_size_request(174, -1)
    shell.pack_start(nav, False, False, 0)
    brand = style(Gtk.Label(label="SocketStream"), "ss-brand")
    brand.set_margin_bottom(25)
    nav.pack_start(brand, False, False, 0)
    app.workspace_stack = Gtk.Stack()
    app.workspace_stack.set_transition_type(Gtk.StackTransitionType.CROSSFADE)
    app.workspace_stack.set_transition_duration(160)
    app.workspace_stack.set_hhomogeneous(False)
    app.workspace_stack.set_vhomogeneous(False)
    shell.pack_start(app.workspace_stack, True, True, 0)
    app.nav_buttons = {}
    for key, title in (("session", "Session"), ("capture", "Capture sources"),
                       ("appearance", "Appearance"), ("shortcuts", "Shortcuts"),
                       ("tools", "Tools & diagnostics")):
        button = Gtk.ToggleButton(label=title)
        button.get_child().set_xalign(0)
        button.connect("clicked", lambda _button, name=key: app.navigate(name))
        nav.pack_start(button, False, False, 0)
        app.nav_buttons[key] = button
    nav.pack_start(Gtk.Box(), True, True, 0)
    nav.pack_start(style(Gtk.Label(label="English speech\nMoonshine · on device"), "ss-muted"), False, False, 12)
    quit_button = style(Gtk.Button(label="Quit SocketStream"), "ss-quiet")
    quit_button.connect("clicked", app.on_exit)
    nav.pack_start(quit_button, False, False, 0)
    app.footer_status = style(Gtk.Label(label="Ready · Capture starts when you choose a source."), "ss-muted")
    app.footer_status.set_xalign(0)
    app.footer_status.set_margin_start(20)
    app.footer_status.set_margin_top(8)
    app.footer_status.set_margin_bottom(8)
    app.footer_status.set_ellipsize(Pango.EllipsizeMode.END)
    root.pack_end(app.footer_status, False, False, 0)

    def label(text, css="ss-muted"):
        widget = style(Gtk.Label(label=text), css)
        widget.set_xalign(0)
        widget.set_line_wrap(True)
        widget.set_line_wrap_mode(Pango.WrapMode.WORD_CHAR)
        widget.set_max_width_chars(65)
        return widget

    def page(key, title, subtitle):
        scroller = Gtk.ScrolledWindow()
        scroller.set_policy(Gtk.PolicyType.NEVER, Gtk.PolicyType.AUTOMATIC)
        box = Gtk.Box(orientation=Gtk.Orientation.VERTICAL, spacing=18)
        box.set_border_width(28)
        box.pack_start(label(title, "ss-title"), False, False, 0)
        subtitle_label = label(subtitle)
        box.pack_start(subtitle_label, False, False, 0)
        scroller.add(box)
        app.workspace_stack.add_named(scroller, key)
        return box

    def card(parent, title=None):
        box = style(Gtk.Box(orientation=Gtk.Orientation.VERTICAL, spacing=12), "ss-card")
        if title:
            box.pack_start(label(title, "ss-section-title"), False, False, 0)
        parent.pack_start(box, False, True, 0)
        return box

    def buttons(parent, items):
        row = Gtk.Box(spacing=8)
        parent.pack_start(row, False, False, 0)
        return [app.add_button(row, title, handler) for title, handler in items]

    session = page("session", "Your workspace", "Read, listen, and keep the answer you need.")
    provider_card = card(session)
    provider_row = Gtk.Box(spacing=10)
    provider_card.pack_start(provider_row, False, False, 0)
    provider_row.pack_start(label("AI provider", "ss-section-title"), False, False, 0)
    app.provider = Gtk.ComboBoxText()
    for value in ("mock", "ollama", "codex", "openai-compatible"):
        app.provider.append_text(value)
    app.provider.set_active(3 if app.env.get("SOCKET_STREAM_MODEL") else 1)
    app.provider.connect("changed", lambda *_: app.sync_provider_label())
    provider_row.pack_start(app.provider, True, True, 0)
    app.add_button(provider_row, "Configure", app.settings)
    app.provider_hint = label("")
    provider_card.pack_start(app.provider_hint, False, False, 0)
    sources = Gtk.Box(spacing=14, homogeneous=True)
    session.pack_start(sources, False, False, 0)
    screen = card(sources, "Read the screen")
    screen.pack_start(label("Accessible text first.\nLocal OCR when you enable it."), False, False, 0)
    app.start_button = buttons(screen, [("Start observation", app.start)])[0]
    style(app.start_button, "ss-primary")
    audio = card(sources, "Listen to audio")
    audio.pack_start(label("Microphone or system audio.\nEnglish transcription on device."), False, False, 0)
    app.read_screen_check = Gtk.CheckButton(label="Also read the screen in parallel")
    app.read_screen_check.set_tooltip_text(
        "While listening, keep the latest screen text as context for spoken and typed questions.")
    app.read_screen_check.get_accessible().set_name("Parallel screen reading")
    audio.pack_start(app.read_screen_check, False, False, 0)
    app.listen_button = buttons(audio, [("Listen to audio", app.listen_audio)])[0]
    session_row = Gtk.Box(spacing=8)
    app.status = style(Gtk.Label(label="Stopped"), "ss-chip")
    session_row.pack_start(app.status, False, False, 0)
    session_row.pack_start(Gtk.Box(), True, True, 0)
    app.control_pause_button = app.add_button(session_row, "Pause", app.toggle_pause)
    app.control_pause_button.set_sensitive(False)
    app.control_stop_button = app.add_button(session_row, "Stop", app.stop)
    style(app.control_stop_button, "ss-danger")
    app.control_stop_button.set_sensitive(False)
    app.add_button(session_row, "Minimize app", app.minimize_app)
    session.pack_start(session_row, False, False, 0)
    app.session_message = label("Choose a source to begin. Nothing is being captured.")
    session.pack_start(app.session_message, False, False, 0)
    questions = card(session)
    question_heading = Gtk.Box(spacing=10)
    question_heading.pack_start(label("This session", "ss-section-title"), True, True, 0)
    app.question_count = label("0 questions")
    question_heading.pack_end(app.question_count, False, False, 0)
    questions.pack_start(question_heading, False, False, 0)
    app.current_question = label("Your recognized questions will appear here.")
    questions.pack_start(app.current_question, False, False, 0)
    question_scroll = Gtk.ScrolledWindow()
    question_scroll.set_policy(Gtk.PolicyType.NEVER, Gtk.PolicyType.AUTOMATIC)
    question_scroll.set_min_content_height(100)
    app.session_questions = Gtk.ListBox()
    app.session_questions.set_selection_mode(Gtk.SelectionMode.SINGLE)
    app.session_questions.connect("row-activated", lambda _list, row: app.select_question(row.request_id))
    question_scroll.add(app.session_questions)
    questions.pack_start(question_scroll, True, True, 0)
    selection = Gtk.Box(spacing=8)
    app.workspace_pin_button = app.add_button(selection, "Pin current question", lambda *_: app.floating.toggle_pin())
    app.workspace_pin_button.set_sensitive(False)
    app.workspace_latest_button = app.add_button(selection, "Follow latest", lambda *_: app.floating.follow_latest())
    app.workspace_latest_button.set_sensitive(False)
    questions.pack_start(selection, False, False, 0)

    capture = page("capture", "Capture sources", "Choose what SocketStream can read during a session.")
    screen_options = card(capture, "Screen reading")
    screen_options.pack_start(label("Accessibility tree is the primary source. Protected fields and SocketStream's own windows are excluded."), False, False, 0)
    interval_row = Gtk.Box(spacing=12)
    interval_row.pack_start(label("Read every (seconds)", "ss-small"), True, True, 0)
    app.interval = Gtk.SpinButton.new_with_range(2, 3600, 1)
    app.interval.set_value(5)
    interval_row.pack_end(app.interval, False, False, 0)
    screen_options.pack_start(interval_row, False, False, 0)
    app.force_ocr = Gtk.CheckButton(label="Enable local OCR fallback")
    app.portal = Gtk.CheckButton(label="Use the desktop ScreenCast chooser for OCR")
    screen_options.pack_start(app.force_ocr, False, False, 0)
    screen_options.pack_start(app.portal, False, False, 0)
    exclusion = card(capture, "Floating panel & screen sharing")
    app.capture_label = label("Capture exclusion: checking…", "ss-small")
    exclusion.pack_start(app.capture_label, False, False, 0)
    app.capture_setup_button, app.capture_remove_button, _ = buttons(exclusion, [
        ("Set up exclusion", app.setup_capture_exclusion), ("Remove rule", app.remove_capture_exclusion),
        ("Details", app.show_capture_details)])
    app.capture_restart = label("")
    app.capture_restart.set_no_show_all(True)
    exclusion.pack_start(app.capture_restart, False, False, 0)
    app.stealth = Gtk.CheckButton(label="Stealth overlay · keep the panel above other windows")
    app.stealth.set_active(True)
    app.stealth.set_tooltip_text("Window hints. Capture exclusion is reported separately above.")
    app.stealth.connect("toggled", app.on_stealth_toggled)
    exclusion.pack_start(app.stealth, False, False, 0)
    app.share_status = label("Screen share: checking…")
    exclusion.pack_start(app.share_status, False, False, 0)
    speech = card(capture, "Audio transcription")
    speech.pack_start(label("Bundled Moonshine · English · offline speech recognition. Choose microphone or system audio when you start listening."), False, False, 0)
    buttons(speech, [("Audio devices", app.audio_devices), ("Listen to audio", app.listen_audio)])

    appearance = page("appearance", "Make room for the answer", "Tune your floating panel. Changes preview immediately; Save keeps them for next time.")
    appearance_card = card(appearance, "Reading & transparency")
    font_row = Gtk.Box(spacing=14)
    font_row.pack_start(label("Answer text size", "ss-small"), True, True, 0)
    app.font_size = Gtk.SpinButton.new_with_range(13, 22, 1)
    app.font_size.set_value(app.appearance["font_size"])
    font_row.pack_end(app.font_size, False, False, 0)
    appearance_card.pack_start(font_row, False, False, 0)
    opacity_row = Gtk.Box(spacing=14)
    opacity_row.pack_start(label("Background opacity", "ss-small"), True, True, 0)
    app.opacity_value = label("")
    opacity_row.pack_end(app.opacity_value, False, False, 0)
    appearance_card.pack_start(opacity_row, False, False, 0)
    app.opacity_scale = Gtk.Scale.new_with_range(Gtk.Orientation.HORIZONTAL, 55, 100, 1)
    app.opacity_scale.set_value(app.appearance["opacity"] * 100)
    app.opacity_scale.set_draw_value(False)
    appearance_card.pack_start(app.opacity_scale, False, False, 0)
    appearance_card.pack_start(label("Only the background becomes transparent. Text remains opaque. A desktop compositor is required for transparency."), False, False, 0)
    app.reduced_motion = Gtk.CheckButton(label="Reduce motion")
    app.reduced_motion.set_active(app.appearance["reduced_motion"])
    appearance_card.pack_start(app.reduced_motion, False, False, 0)
    app.cursor_blending_check = Gtk.CheckButton(label="Cursor blending")
    app.cursor_blending_check.set_tooltip_text(
        "Let the answer panel's background pass hover and clicks through to the "
        "window below (X11/XWayland). Turn off to select and scroll the whole panel.")
    app.cursor_blending_check.get_accessible().set_name("Cursor blending")
    app.cursor_blending_check.set_active(bool(getattr(app.floating, "cursor_blending", True)))
    app.cursor_blending_check.connect("toggled", app.on_cursor_blending_toggled)
    appearance_card.pack_start(app.cursor_blending_check, False, False, 0)
    app.cursor_blending_note = label("")
    appearance_card.pack_start(app.cursor_blending_note, False, False, 0)
    if getattr(app.floating, "input_shape_supported", False):
        app.cursor_blending_note.set_text(
            "On: the panel background passes hover and clicks through. "
            "Off: the whole panel accepts selection and scrolling.")
    else:
        app.cursor_blending_check.set_sensitive(False)
        app.cursor_blending_note.set_text(
            "Cursor blending needs X11 or XWayland. This session is native Wayland, "
            "so the whole panel accepts input.")
    app.font_size.connect("value-changed", app.preview_appearance)
    app.opacity_scale.connect("value-changed", app.preview_appearance)
    app.reduced_motion.connect("toggled", app.preview_appearance)
    save_appearance, _ = buttons(appearance, [("Save appearance", app.save_appearance), ("Preview answer panel", app.show_answer_panel)])
    style(save_appearance, "ss-primary")
    app.appearance_message = label("")
    appearance.pack_start(app.appearance_message, False, False, 0)

    shortcuts = page("shortcuts", "Keyboard shortcuts", "Choose the keys that fit your workflow.")
    shortcuts.pack_start(style(label("In-app shortcuts · active while the SocketStream control window is focused.", "ss-small"), "ss-banner"), False, False, 0)
    app.shortcut_enabled = Gtk.CheckButton(label="Enable keyboard shortcuts")
    shortcuts.pack_start(app.shortcut_enabled, False, False, 0)
    shortcut_card = card(shortcuts)
    grid = Gtk.Grid(column_spacing=18, row_spacing=9)
    shortcut_card.pack_start(grid, False, False, 0)
    app.shortcut_entries = {}
    for row, action in enumerate(ACTIONS):
        name = label(ACTION_LABELS[action], "ss-small")
        name.set_hexpand(True)
        grid.attach(name, 0, row, 1, 1)
        entry = style(Gtk.Entry(), "ss-shortcut")
        entry.set_width_chars(23)
        entry.set_tooltip_text("Type a binding such as Ctrl+Alt+B, or use Record")
        entry.get_accessible().set_name(ACTION_LABELS[action] + " shortcut")
        entry.connect("key-press-event", app.record_shortcut_key, action)
        app.shortcut_entries[action] = entry
        grid.attach(entry, 1, row, 1, 1)
        record = Gtk.Button.new_from_icon_name("document-edit-symbolic", Gtk.IconSize.MENU)
        record.set_tooltip_text("Record shortcut for " + ACTION_LABELS[action])
        record.get_accessible().set_name("Record " + ACTION_LABELS[action])
        record.connect("clicked", lambda _button, name=action: app.record_shortcut(name))
        grid.attach(record, 2, row, 1, 1)
    app.shortcut_message = label("")
    shortcuts.pack_start(app.shortcut_message, False, False, 0)
    save_shortcuts, _ = buttons(shortcuts, [("Save shortcuts", app.save_shortcuts), ("Reset to defaults", app.reset_shortcuts)])
    style(save_shortcuts, "ss-primary")
    shortcuts.pack_start(label("Use Ctrl, Alt, Shift or Meta with a letter, number, arrow or function key. Duplicates are checked before saving. Reset takes effect when saved."), False, False, 0)

    tools = page("tools", "Tools & diagnostics", "Import a practice question, check a provider, or inspect a session.")
    imports = card(tools, "Practice material")
    buttons(imports, [("Analyze text", app.choose_file), ("Analyze image", app.choose_image), ("Analyze audio", app.analyze_audio)])
    buttons(imports, [("Audio practice", app.audio_practice), ("Replay demo", app.replay_demo)])
    providers = card(tools, "Provider tools")
    buttons(providers, [("List provider models", app.provider_models), ("Test AI response", app.provider_test), ("Doctor", app.doctor)])
    buttons(providers, [("Start local AI", app.start_local_ai), ("Stop local AI", app.stop_local_ai)])
    buttons(providers, [("Codex sign-in", app.codex_login), ("Codex status", app.codex_status), ("Codex sign-out", app.codex_logout)])
    buttons(providers, [("Session status", lambda *_: app._refresh_question())])
    advanced = Gtk.Expander(label="Advanced tools and diagnostics")
    advanced.set_expanded(True)
    tools.pack_start(advanced, True, True, 0)
    logs = Gtk.ScrolledWindow()
    logs.set_min_content_height(200)
    app.output = style(Gtk.TextView(), "ss-diagnostics")
    app.output.set_editable(False)
    app.output.set_cursor_visible(False)
    app.output.set_monospace(True)
    app.output.set_wrap_mode(Gtk.WrapMode.WORD_CHAR)
    app.output.set_left_margin(12)
    app.output.set_right_margin(12)
    logs.add(app.output)
    advanced.add(logs)
    app.navigate("session")
